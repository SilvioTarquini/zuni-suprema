function buscarLivro(livroId) {
  return CATALOGO[livroId] || null;
}

// Serialização pública do catálogo (GET /api/livros e /api/livros/catalogo/:id).
// A loja precisa saber SE a obra tem audiobook e QUANTO custa (audiobookDisponivel,
// precoAudiobook), nunca ONDE está o arquivo: audiobookUrl/audiobookPartes
// (legacy) e audiobookStorage (bucket privado) só são lidos internamente, pela
// rota autenticada /audiolivros/:livroId. Não cria cópia mutável do
// catálogo-fonte (devolve objetos novos).
// indicadoPara é metadado interno consumido só pelo prompt do Mentor.
function serializarLivroPublico(livro) {
  const { indicadoPara, audiobookUrl, audiobookPartes, audiobookStorage, ...publico } = livro;
  return publico;
}

// A estrutura interna continua indexada por livroId para os lookups do servidor.
// A vitrine, por outro lado, recebe uma lista: cada item já carrega seu livroId e
// pode ser filtrado/ordenado com os métodos nativos de Array.
function listarLivrosPublicos() {
  return Object.entries(CATALOGO)
    .filter(([, livro]) => !livro.teaser)
    .map(([livroId, livro]) => ({ livroId, ...serializarLivroPublico(livro) }));
}

function serializarLivroCatalogo(livroId, livro) {
  return {
    livroId,
    titulo: livro.titulo,
    preco: livro.precoPromocional || livro.preco,
    categoria: livro.categoria,
    audiobookDisponivel: livro.audiobookDisponivel || false,
    precoAudiobook: livro.precoAudiobook || null
  };
}

